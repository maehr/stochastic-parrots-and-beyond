#!/usr/bin/env python3
"""Build the timetable files of the course day from ``data/schedule.yml``.

The schedule is the single source for three generated files:

- ``contents/_timetable.qmd``: the timetable for participants.
- ``contents/_trainer-timeline.qmd``: the trainer timeline with the lead.
- ``contents/slides/_day-slots.qmd``: the all-day slide deck. Each slot gets a
  title slide, then the slides of its ``parts`` from ``contents/slides/_parts/``.

The generated files are committed. ``test/test_schedule.py`` fails when a file
is out of date.

Usage:
    uv run python scripts/build_schedule.py           # write the files
    uv run python scripts/build_schedule.py --check   # fail if a file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
SCHEDULE = REPO_ROOT / "data" / "schedule.yml"
CONTENTS = REPO_ROOT / "contents"
TIMETABLE = CONTENTS / "_timetable.qmd"
TRAINER_TIMELINE = CONTENTS / "_trainer-timeline.qmd"
DAY_SLOTS = CONTENTS / "slides" / "_day-slots.qmd"
PLENARY_QUESTIONS = CONTENTS / "_plenary-questions.qmd"
LENS_QUESTIONS = CONTENTS / "lenses" / "_guiding-questions-{n:02d}.qmd"
PARTS_DIR = CONTENTS / "slides" / "_parts"
# License slides that open the all-day deck, before the first slot.
DAY_LICENSE_PARTS = ["00-license.qmd", "05-license.qmd"]

FORMATS = ("Plenary", "Alone", "Pairs", "Groups", "Break")
HEADER = (
    "<!-- Generated by scripts/build_schedule.py from data/schedule.yml. "
    "Do not edit. Run npm run schedule:build. -->"
)


def minutes(clock: str) -> int:
    hours, mins = clock.split(":")
    return int(hours) * 60 + int(mins)


def load(path: Path = SCHEDULE) -> list[dict]:
    with path.open(encoding="utf-8") as f:
        slots = yaml.safe_load(f)["slots"]
    for prev, slot in zip(slots, slots[1:], strict=False):
        if prev["end"] != slot["start"]:
            sys.exit(
                f"{slot['activity']} starts at {slot['start']}, not {prev['end']}."
            )
    for slot in slots:
        if slot["format"] not in FORMATS:
            sys.exit(f"{slot['activity']}: unknown format {slot['format']!r}.")
        if minutes(slot["end"]) <= minutes(slot["start"]):
            sys.exit(f"{slot['activity']} ends before it starts.")
    return slots


def duration(slot: dict) -> int:
    return minutes(slot["end"]) - minutes(slot["start"])


def time_range(slot: dict) -> str:
    return f"{slot['start']}–{slot['end']}"


def format_label(slot: dict) -> str:
    return "—" if slot["format"] == "Break" else slot["format"]


def table(head: list[str], rows: list[list[str]], caption: str) -> str:
    """Return a Markdown pipe table in the layout that Prettier writes."""
    widths = [max(3, len(h), *(len(r[i]) for r in rows)) for i, h in enumerate(head)]

    def line(cells: list[str]) -> str:
        return (
            "| "
            + " | ".join(c.ljust(w) for c, w in zip(cells, widths, strict=True))
            + " |"
        )

    out = [line(head), "| " + " | ".join("-" * w for w in widths) + " |"]
    out += [line(r) for r in rows]
    return "\n".join(out) + f"\n\n: {caption} {{.striped}}\n"


def activity_cell(slot: dict) -> str:
    link = slot.get("link")
    return f"[{slot['activity']}]({link})" if link else slot["activity"]


def timetable(slots: list[dict]) -> str:
    rows = [[time_range(s), activity_cell(s), format_label(s)] for s in slots]
    body = table(["Time", "Activity", "Format"], rows, "Timetable of the course day")
    return f"{HEADER}\n\n{body}"


def trainer_timeline(slots: list[dict]) -> str:
    rows = [
        [time_range(s), s["activity"], format_label(s), s.get("lead") or "—"]
        for s in slots
    ]
    caption = (
        "Trainer timeline. Both trainers facilitate during collaborative activities."
    )
    body = table(["Time", "Activity", "Format", "Lead"], rows, caption)
    return f"{HEADER}\n\n{body}"


def read_include(path: Path) -> str:
    return path.read_text(encoding="utf-8").strip()


def lens_questions_block(slots: list[dict]) -> str:
    names = {}
    for slot in slots:
        link = slot.get("link") or ""
        if link.startswith("/contents/lenses/"):
            names[int(Path(link).name[:2])] = slot["activity"]
    cells = []
    for n in sorted(names):
        questions = read_include(Path(str(LENS_QUESTIONS).format(n=n)))
        cells.append(f"::: {{.lens-cell}}\n\n**{names[n]}**\n\n{questions}\n\n:::")
    return ":::: {.lens-grid}\n\n" + "\n\n".join(cells) + "\n\n::::"


def day_slots(slots: list[dict]) -> str:
    blocks = {
        "lens-questions": lens_questions_block(slots),
        "plenary-questions": read_include(PLENARY_QUESTIONS),
    }
    out = [HEADER, include_lines(DAY_LICENSE_PARTS)]
    for slot in slots:
        meta = [time_range(slot), f"{duration(slot)} min"]
        if slot["format"] != "Break":
            meta.append(slot["format"])
        if slot.get("lead"):
            meta.append(f"Lead: {slot['lead']}")
        # Sixteen guiding questions fit on one slide only in the smaller size.
        dense = slot.get("display_block") == "lens-questions"
        classes = ".day-slot"
        if slot["format"] == "Break":
            classes += " .break"
        if dense:
            classes += " .smaller"
        title = [
            f"## {slot['activity']} {{{classes}}}",
            f"[{' · '.join(meta)}]{{.slot-meta}}",
            slot["display"].strip(),
        ]
        if slot.get("display_block"):
            title.append(blocks[slot["display_block"]])
        out.append("\n\n".join(title))
        if slot.get("parts"):
            out.append(include_lines(slot["parts"]))
    return "\n\n".join(out) + "\n"


def include_lines(names: list[str]) -> str:
    return "\n".join(f"{{{{< include _parts/{name} >}}}}" for name in names)


def build() -> dict[Path, str]:
    slots = load()
    return {
        TIMETABLE: timetable(slots),
        TRAINER_TIMELINE: trainer_timeline(slots),
        DAY_SLOTS: day_slots(slots),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Fail if a file is stale.")
    args = parser.parse_args()

    stale = []
    for path, text in build().items():
        rel = path.relative_to(REPO_ROOT)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(str(rel))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"data/schedule.yml -> {rel}")
    if stale:
        print(f"Out of date: {', '.join(stale)}. Run npm run schedule:build.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
